"""Run the example questions through the submitted system and write EXAMPLES.md with the real outputs.
  uv run python scripts/make_examples.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

QUESTIONS = [
    ("Contract (born-digital)", "What is the maximum compensation a contractor pays for delay in completing the work, and who decides it?"),
    ("Schedule of rates (table)", "What is the rate of a 15 mm CP brass pillar cock?"),
    ("Schedule of rates, near-miss", "What is the rate of a 20 mm CP brass pillar cock?"),
    ("Schedule of rates, item code + note", "What is the rate for item S-1.1.1, and how much extra if a light coloured pan is used?"),
    ("Tender scan, English question over Hindi text", "What is the EMD for the Yatri Niwas tender if I am registered outside the division?"),
    ("Tender scan, Hindi question", "इस निविदा का UBN नंबर क्या है?"),
    ("Tender scan, OCR-corrected value", "What is the last date and time for submitting bids online?"),
    ("Non-existent clause", "What does Clause 47 of the contract say about a bonus for early completion?"),
    ("Out of scope", "What is the minimum cement content for M25 concrete as per IS 456?"),
]


def main() -> None:
    from cosorag.answer import answer
    from cosorag.index import Index
    from cosorag.llm import LLM

    ix, llm = Index.build(), LLM()
    md = ["# Example answers", "",
          "Real outputs of the submitted system (gpt-oss-120b on Bedrock, fine-tuned reranker and gate), generated by",
          "`scripts/make_examples.py`. Citations give document, locator and printed page (with the PDF page when they differ).", ""]
    for kind, q in QUESTIONS:
        a = answer(ix, q, llm=llm)
        status = "verified" if a.checks.get("ok") else ("declined: not in the documents" if not a.answerable else "verifier warning")
        md += [f"## {kind}", "", f"**Q:** {q}", "", f"**A** ({status}): {a.answer}", ""]
        for c in a.citations:
            md.append(f"- [S{c['n']}] {c['cite']}" + (f": \"{c['quote'][:200]}\"" if c.get("quote") else ""))
        if a.retrieval and any(not lk["found"] for lk in a.retrieval.id_lookups):
            md.append(f"- Lookup: {', '.join(lk['id'] for lk in a.retrieval.id_lookups if not lk['found'])} does not exist in the indexed documents")
        if a.gate:
            md.append(f"- Grounding gate: {a.gate}")
        md.append("")
        print(f"[{kind}] {status}: {a.answer[:120]}")
    (ROOT / "EXAMPLES.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote EXAMPLES.md")


if __name__ == "__main__":
    main()
